#!/usr/bin/env python3
# released from gs-paper at b95936d (evidence/front-by-part-49-layouts-i01/tab_front_by_part_49_layouts_w16_ab_wops.py); edit it there, then run evidence/release_draw.py
"""Paper table (the appendix): Figure 10 (e) as numbers. A's and B's wops (the best mix within 2x and 5x Sp-Co's bytes),
part by part: the setting each part gets, its wops as a multiple of Sp-Co's, and its share of the mix's wops (the tabular
only).

  tables/front-49-ab-wops.tex

A part is listed if it is at least 2% of A's or B's wops; the rest are one "other" row; then the totals.

Reads only its tables: front-by-part-49-layouts-i01.csv (the mixes on the front, each part's setting and wops) and
front-by-part-49-layouts-i01-points.csv (Sp-Co's totals).

    python tab_front_by_part_49_layouts_w16_ab_wops.py --data <dir of the tables> --out <dir>
"""
from common import args, read_table

BUDGETS = (("A", 2.0), ("B", 5.0))
REF = "props_split_adj_condensed"
LISTED = 0.02                  # a part's share of A's or B's wops to get its own row
SHORT = {"split": "Sp", "condensed": "Co", "chunked_c1k": "Ch1k", "chunked_c4k": "Ch4k", "chunked_c16k": "Ch16k",
         "chunked": "Ch64k", "chunked_c256k": "Ch256k"}


def main():
    data, out_dir = args(__doc__)
    ref = [p for p in read_table(data, "front-by-part-49-layouts-i01-points") if p["kind"] == "uniform49" and p["name"] == REF]
    if len(ref) != 1:
        raise SystemExit(f"points: {len(ref)} {REF} rows")
    w0 = float(ref[0]["wops"])
    mixes = {}
    for r in read_table(data, "front-by-part-49-layouts-i01"):
        if r["source"] == "solved":
            m = mixes.setdefault(r["mix"], {"w": float(r["wops"]) / w0, "b": float(r["bytes"]) / float(ref[0]["bytes"]),
                                            "parts": {}})
            m["parts"][(r["kind"], r["part"])] = (r["setting"], float(r["part_wops"]) / w0)
    cols = []
    for name, lim in BUDGETS:
        mix = min((m for m in mixes.values() if m["b"] <= lim * (1 + 1e-9)), key=lambda m: m["w"])
        total = sum(w for _, w in mix["parts"].values())
        if abs(total / mix["w"] - 1) > 1e-6:
            raise SystemExit(f"{name}: its parts' wops {total} are not its wops {mix['w']}")
        cols.append((name, lim, mix, total))
        print(f"{name}: {total:.3f} of Sp-Co's wops, {mix['b']:.2f} of its bytes")
    keys = [k for k in cols[0][2]["parts"] if any(c[2]["parts"][k][1] / c[3] >= LISTED for c in cols)]
    keys.sort(key=lambda k: (k[0] == "index", k[0] == "props", -cols[0][2]["parts"][k][1]))   # by A's wops; props, index last

    def num(v):
        return f"{v:.3f}".replace("0.", ".", 1)

    lines = [r"% GENERATED by tab_front_by_part_49_layouts_w16_ab_wops.py (gs-paper evidence/front-by-part-49-layouts-i01/) -- do not edit",
             r"\begin{tabular}{@{}l" + "lrr" * len(cols) + r"@{}}", r"\toprule",
             " & " + " & ".join(rf"\multicolumn{{3}}{{c{'@{}' if i == len(cols) - 1 else ''}}}{{{n}: {lim:g}$\times$ bytes}}"
                                for i, (n, lim, _, _) in enumerate(cols)) + r" \\",
             "".join(rf"\cmidrule(l{{2pt}}){{{2 + 3 * i}-{4 + 3 * i}}}" for i in range(len(cols))),
             "Part & " + " & ".join(r"setting & $\mathit{wops}$ & share" for _ in cols) + r" \\", r"\midrule"]
    for k in keys:
        cells = []
        for _, _, mix, total in cols:
            s, w = mix["parts"][k]
            cells += ["" if k[0] == "index" else SHORT[s], num(w), f"{100 * w / total:.0f}\\%"]
        name = "index" if k[0] == "index" else k[1] + (" (V)" if k[0] == "props" else "")
        lines.append(f"{name} & " + " & ".join(cells) + r" \\")
    other = []
    for _, _, mix, total in cols:
        w = sum(v for kk, (_, v) in mix["parts"].items() if kk not in keys)
        other += ["", num(w), f"{100 * w / total:.0f}\\%"]
    lines.append("other parts & " + " & ".join(other) + r" \\")
    lines.append(r"\midrule")
    lines.append("Total & " + " & ".join(f" & {num(total)} & 100\\%" for _, _, _, total in cols) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    out = out_dir / "tables" / "front-49-ab-wops.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out}: {len(keys)} parts and the other row")


if __name__ == "__main__":
    main()
