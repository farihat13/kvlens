#!/usr/bin/env python3
# released from gs-paper at d898cce (evidence/datasets/tab_datasets.py); edit it there, then run evidence/release_draw.py
"""Paper table: the datasets, with their workloads, vertex and edge counts, types, and the store's size as Sp-Sp (the
largest uniform layout) and as Ch256k-Ch256k (the tabular only; the draft writes the table, caption and label).

  tables/datasets.tex   (and .md: the same rows, for a reader)

Size = the store's SST bytes in GB (10^9 bytes), as the store was built (the artifact's store_config). Counts: millions, one decimal below 100M.
Workloads: the ones the paper runs on each dataset (WORKLOADS below, by the dataset's name before its scale).

Reads only its two tables: datasets.csv (the artifact's paper/derive/datasets.py makes it from the store manifests: per
dataset, row = the table's order, the vertices, edges, vertex and edge types) and datasets-sizes.csv (per dataset and
layout, the SST bytes; the two must agree on Sp-Sp).

    python tab_datasets.py --data <dir of datasets.csv> --out <dir>     # -> <out>/tables/datasets.tex
"""
from common import args, read_table, write_table

LAYOUTS = ("props_split_adj_split", "props_chunked_c256k_adj_chunked_c256k")     # Sp-Sp, and Ch256k-Ch256k
COUNTS = ("vertices", "edges", "vertex_types", "edge_types")
WORKLOADS = {"LDBC SNB": "Interactive, BI", "IMDb": "JOB", "LinkBench": "LinkBench"}     # by the name before ", <scale>"


def millions(n):
    return f"{n / 1e6:.1f}M" if n < 1e8 else f"{n / 1e6:.0f}M"


def main():
    data, out_dir = args(__doc__)
    by_row = {}
    for r in read_table(data, "datasets"):
        by_row.setdefault(int(r["row"]), []).append(r)
    sizes = {(int(r["row"]), r["layout"]): r for r in read_table(data, "datasets-sizes")}
    lines = [r"% GENERATED by tab_datasets.py (gs-paper evidence/datasets/) from datasets.csv and datasets-sizes.csv -- do not edit",
             r"\begin{tabular}{@{}llrrcrr@{}}", r"\toprule",
             r"Dataset & Workloads & Vertices & Edges & Types & \multicolumn{2}{c@{}}{Size (GB)} \\",
             r"\cmidrule(l){6-7}",
             r" & & & & V / E & Sp-Sp & Ch256k-Ch256k \\", r"\midrule"]
    for i in sorted(by_row):
        rows = {r["layout"]: r for r in by_row[i]}
        if len({r["dataset"] for r in rows.values()}) != 1 or len({tuple(r[k] for k in COUNTS) for r in rows.values()}) != 1:
            raise SystemExit(f"row {i}: the layouts disagree on the dataset or its counts")
        any_ = next(iter(rows.values()))
        name = any_["dataset"]
        base = name.split(",")[0]
        size = {c: sizes.get((i, c)) for c in LAYOUTS}
        if any(r is None or r["dataset"] != name for r in size.values()) or base not in WORKLOADS:
            raise SystemExit(f"row {i} ({name}): a size missing from datasets-sizes.csv, or no workloads")
        if size[LAYOUTS[0]]["sst_bytes"] != rows[LAYOUTS[0]]["sst_bytes"]:
            raise SystemExit(f"row {i} ({name}): the two tables disagree on Sp-Sp's size")
        v, e, vt, et = (int(any_[k]) for k in COUNTS)
        gb = [f"{int(size[c]['sst_bytes']) / 1e9:.1f}" for c in LAYOUTS]
        lines.append(f"{name} & {WORKLOADS[base]} & {millions(v)} & {millions(e)} & {vt} / {et} & {gb[0]} & {gb[1]} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    out = out_dir / "tables" / "datasets.tex"
    write_table(out, lines, "The datasets: their workloads, vertex and edge counts, types, and the store's size as Sp-Sp (the largest uniform layout) and as Ch256k-Ch256k.")


if __name__ == "__main__":
    main()
