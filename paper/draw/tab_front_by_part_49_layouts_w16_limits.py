#!/usr/bin/env python3
# released from gs-paper at b95936d (evidence/front-by-part-49-layouts-i01/tab_front_by_part_49_layouts_w16_limits.py); edit it there, then run evidence/release_draw.py
"""Paper table (the appendix): Figure 10 (a)'s fronts as numbers. At each byte limit, the fewest wops of the best uniform
layout and of the best mix, for the 49 uniform layouts against the mixes over the 7 settings, and for the nine at 64 KB
against the mixes over their 3 settings (the tabular only).

  tables/front-49-limits.tex

wops and bytes are multiples of Sp-Co's; a set's best at a limit is its fewest wops among its points within that many
times Sp-Co's bytes; the ratio is the uniform layout's wops over the mix's. The last row, per side, is the largest ratio
over every limit (a set's best changes only at one of its points' bytes, so those are the limits checked), with its limit.

Reads only its tables: front-by-part-49-layouts-i01-points.csv (the 49, the nine, the 3-setting mixes) and
front-by-part-49-layouts-i01.csv (the 7-setting front's mixes; with the 3-setting mixes, the candidates Figure 10's
front is drawn from).

    python tab_front_by_part_49_layouts_w16_limits.py --data <dir of the tables> --out <dir>
"""
from common import args, read_table

LIMITS = (1, 1.25, 1.5, 2, 3, 5, 7, 10, 20)
REF = "props_split_adj_condensed"
SHORT = {"split": "Sp", "condensed": "Co", "chunked": "Ch64k"}


def short(cell):
    """props_X_adj_Y -> X-Y, e.g. Ch4k-Co"""
    p, a = cell[len("props_"):].split("_adj_")
    return "-".join(SHORT.get(s) or "Ch" + s.split("_c")[1] for s in (p, a))


def best(points, limit):
    """(wops, bytes, name) with the fewest wops within `limit` x Sp-Co's bytes"""
    within = [p for p in points if p[1] <= limit * (1 + 1e-9)]
    if not within:
        raise SystemExit(f"no point within {limit}x Sp-Co's bytes")
    return min(within)


def largest(uni, mix):
    """(ratio, limit, uniform, mix) with the largest uniform-over-mix wops over every limit"""
    out = []
    for lim in sorted({p[1] for p in uni + mix}):
        if any(p[1] <= lim for p in uni) and any(p[1] <= lim for p in mix):
            u, m = best(uni, lim), best(mix, lim)
            out.append((u[0] / m[0], lim, u, m))
    return max(out)


def main():
    data, out_dir = args(__doc__)
    pts = read_table(data, "front-by-part-49-layouts-i01-points")
    ref = [p for p in pts if p["kind"] == "uniform49" and p["name"] == REF]
    if len(ref) != 1:
        raise SystemExit(f"points: {len(ref)} {REF} rows")
    w0, b0 = float(ref[0]["wops"]), float(ref[0]["bytes"])

    def scaled(rows, name=lambda r: r["name"]):
        return [(float(r["wops"]) / w0, float(r["bytes"]) / b0, name(r)) for r in rows]

    u49 = scaled([p for p in pts if p["kind"] == "uniform49"])
    u9 = scaled([p for p in pts if p["kind"] == "uniform9"])
    mix3 = scaled([p for p in pts if p["kind"] == "front3"], lambda r: "")
    mixes = {}
    for r in read_table(data, "front-by-part-49-layouts-i01"):   # one row per (mix, part): a mix's totals repeat
        mixes[(r["source"], r["mix"])] = r
    mix7 = scaled(mixes.values(), lambda r: "") + mix3            # the 3-setting mixes are 7-setting mixes too
    if (len(u49), len(u9)) != (49, 9):
        raise SystemExit(f"points: {len(u49)} uniform49 and {len(u9)} uniform9 rows (want 49, 9)")

    lines = [r"% GENERATED by tab_front_by_part_49_layouts_w16_limits.py (gs-paper evidence/front-by-part-49-layouts-i01/) -- do not edit",
             r"\begin{tabular}{@{}r lrrr lrrr@{}}", r"\toprule",
             r" & \multicolumn{4}{c}{7 settings (Sp, Co, Ch1k--256k)} & \multicolumn{4}{c@{}}{3 settings (Sp, Co, Ch64k)} \\",
             r"\cmidrule(l{2pt}){2-5}\cmidrule(l{2pt}){6-9}",
             r"bytes & \multicolumn{2}{c}{best uniform} & mix & ratio & \multicolumn{2}{c}{best uniform} & mix & ratio \\",
             r"\midrule"]
    for lim in LIMITS:
        cells = [f"{lim:g}$\\times$"]
        for uni, mix in ((u49, mix7), (u9, mix3)):
            u, m = best(uni, lim), best(mix, lim)
            cells += [short(u[2]), f"{u[0]:.3f}", f"{m[0]:.3f}", f"{u[0] / m[0]:.2f}$\\times$"]
        lines.append(" & ".join(cells) + r" \\")
        print(" | ".join(cells))
    cells, at = ["largest"], [""]                     # the limit on a second line, under the layout's name
    for uni, mix in ((u49, mix7), (u9, mix3)):
        r, lim, u, m = largest(uni, mix)
        cells += [short(u[2]), f"{u[0]:.3f}", f"{m[0]:.3f}", f"{r:.2f}$\\times$"]
        at += [f"(at {lim:.3f}$\\times$)", "", "", ""]
    lines += [r"\midrule", " & ".join(cells) + r" \\", " & ".join(at) + r" \\"]
    print(" | ".join(cells), "|", " ".join(at))
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    out = out_dir / "tables" / "front-49-limits.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out}: {len(LIMITS)} limits")


if __name__ == "__main__":
    main()
