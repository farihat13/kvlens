#!/usr/bin/env python3
# released from gs-paper at 76dbba8 (evidence/composed-vs-measured/tab_composed_vs_measured.py); edit it there, then run evidence/release_draw.py
"""Paper table: composed against measured KV cost, every committed check (the tabular only; the draft writes the
table, caption and label). main.tex does not read it; the text gives its 99.99998%.

  tables/composed-vs-measured.tex

"Ops equal" = every operation count (S, G, N, P, D) of every step row; "Bytes equal" = the share of the bytes (all lanes)
that equal the measured, "all" when none differ.

Reads only its table, composed-vs-measured.csv (the artifact's paper/derive/composed_vs_measured.py makes it from the
checks' snapshots): per check, its label, scale, layouts, step rows, and the byte difference and measured bytes.

    python tab_composed_vs_measured.py --data <dir of composed-vs-measured.csv> --out <dir>
"""
import math

from common import args, read_table


def share_equal(diff, total):
    """'all' when nothing differs; else the equal share, rounded down so a difference never prints as 100%"""
    if diff == 0:
        return "all"
    return f"{math.floor((1 - diff / total) * 1e7) / 1e5:.5f}\\%"


def main():
    data, out_dir = args(__doc__)
    rows = sorted(read_table(data, "composed-vs-measured"), key=lambda r: int(r["row"]))
    lines = [r"% GENERATED by tab_composed_vs_measured.py (gs-paper evidence/composed-vs-measured/) from composed-vs-measured.csv -- do not edit",
             r"\begin{tabular}{@{}lrrrr@{}}", r"\toprule",
             r"Layouts & Data & Rows & Ops & Bytes \\", r"\midrule"]
    for r in rows:
        byt = share_equal(float(r["bytes_differ"]), float(r["bytes_measured"]) if r["bytes_measured"] else 0.0)
        lines.append(f"{r['layouts']} {r['label']} & {r['scale']} & {int(r['rows']):,} & {r['ops']} & {byt} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    out = out_dir / "tables" / "composed-vs-measured.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
