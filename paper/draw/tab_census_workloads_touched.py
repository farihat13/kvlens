#!/usr/bin/env python3
# released from gs-paper at d898cce (evidence/census-workloads/tab_census_workloads_touched.py); edit it there, then run evidence/release_draw.py
"""Paper table: each workload's KV operations on Sp-Sp by kind, at its own weighting (the tabular only; the draft writes the
caption and label).

  tables/census-workloads-touched.tex   (and .md: the same rows, for a reader)

Rows: LDBC Interactive, LDBC BI, JOB, LinkBench (named Interactive and BI; the caption says LDBC). Columns: adjacency lists read without edge properties, adjacency lists
read with their edge properties, edge properties read directly (a single-edge probe), vertex properties, index, written;
each the share (%) of the workload's KV ops on Sp-Sp (Split keeps one item per KV pair): S + G + N on the part, misses
included, and P + D written. Weights: Interactive LDBC's frequencies, BI and JOB an equal share of Sp-Co's op-byte cost
per query, LinkBench its 100,000-request log. A share under 0.5% that is not zero prints as <1.

Reads only census-workloads-ops.csv (the README says where it comes from).

    python tab_census_workloads_touched.py --data <dir of the tables> --out <dir>
"""
from common import args, read_table, write_table

COLUMNS = ("adj", "adj_ep", "ep", "props", "index", "written")
# two header rows: the adjacency group over its two columns; every other column one block over both rows (\multirow,
# \makecell: macros.tex loads both)
ONE = (r"\makecell{Edge props\\direct}", r"\makecell{Vertex\\props}", "Index", "Writes")
HEAD = (r" & \multicolumn{2}{c}{Adjacency lists} & " + " & ".join(rf"\multirow{{2}}{{*}}{{{h}}}" for h in ONE)
        + r" \\ \cmidrule(lr){2-3}",
        r" & alone & + edge props" + " &" * len(ONE) + r" \\")
ROWS = (("ldbc", "Interactive", "frequency"), ("bi", "BI", "equal_share"), ("job", "JOB", "equal_share"),
        ("linkbench", "LinkBench", "frequency"))


def pct(x):
    """a share as a whole percent; a share that is not zero but rounds to 0 prints as <1"""
    if x == 0:
        return "0"
    return "$<$1" if x < 0.005 else f"{x * 100:.0f}"


def main():
    data, out_dir = args(__doc__)
    rows = read_table(data, "census-workloads-ops")
    lines = [r"% GENERATED by tab_census_workloads_touched.py (gs-paper evidence/census-workloads/) from "
             r"census-workloads-ops.csv -- do not edit",
             r"\begin{tabular}{@{}l" + "r" * len(COLUMNS) + r"@{}}", r"\toprule", *HEAD, r"\midrule"]
    for fam, name, how in ROWS:
        t = {k: sum(float(r[how]) * float(r[f"sp_{k}"]) for r in rows if r["family"] == fam) for k in COLUMNS}
        n = sum(t.values())
        if n == 0:                # a workload this run did not measure (the small set has no LinkBench): no row
            print(f"{name}: not in this run")
            continue
        lines.append(f"{name} & " + " & ".join(pct(t[k] / n) for k in COLUMNS) + r" \\")
        print(f"{name}: " + "  ".join(f"{k} {t[k] / n:.4f}" for k in COLUMNS))
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    out = out_dir / "tables" / "census-workloads-touched.tex"
    write_table(out, lines, "Each workload's KV operations on Sp-Sp by kind, at its own weighting: the share (%) of its KV operations on each part.")


if __name__ == "__main__":
    main()
