#!/usr/bin/env python3
# released from gs-paper at ebdd331 (evidence/run-time/tab_run_time.py); edit it there, then run evidence/release_draw.py
"""Paper table: what choosing among the 49 uniform layouts costs at SF3, by measuring and by predicting, and what
finding the best mix costs (the tabular only; the draft writes the table, caption and label).

  tables/run-time.tex

Columns: LDBC Interactive, LDBC BI, JOB. Measure: build the seven diagonal stores (the 49 are composed from them), run
the workload on each. First two rows: the workload's queries and their candidate plans (both routes run or price every
plan). Predict: the statistics, one tally per setting, predict the 49; no store, no query run. A step
two workloads share (LDBC's stores, statistics and tallies) spans their columns and counts in each one's total. Totals
sum the records one after another. Best mix (op-byte cost, no store): find in two stages, (a) each query's plan fixed
at its pick under the best uniform layout and each part alone at its cheapest setting, then (b) one part at a time with
plans re-picked; then verify (the branch and bound; a verify stopped early shows the gap to its bound). Beside the
measure route, not in its total: compose the other 42 layouts from the seven and cost the 49 (the composed layouts'
records and cost-layouts' run), -- when the tables hold no such row.

Reads only its tables (the artifact's paper/derive/run_time.py makes them from the pinned snapshots): run-time.csv (one
row per run record: route, step, workload, wall_s, proven, gap) and run-time-search-size.csv (queries, plans).

    python tab_run_time.py --data <dir of the tables> --out <dir>     # -> <out>/tables/run-time.tex
"""
from common import args, read_table, write_table

WORKLOADS = ("Interactive", "BI", "JOB")
SHARED = {"Interactive": "LDBC", "BI": "LDBC", "JOB": "IMDb"}


def human(s):
    """a wall time as text: seconds (one decimal under 10 s), minutes, then hours with one decimal"""
    if s < 10:
        return f"{s:.1f}\\,s"
    if s < 90:
        return f"{int(s + 0.5)}\\,s"
    if s < 90 * 60:
        return f"{int(s / 60 + 0.5)}\\,min"
    return f"{s / 3600:.1f}\\,h"


def main():
    data, out_dir = args(__doc__)
    rows = read_table(data, "run-time")
    size = {r["workload"]: r for r in read_table(data, "run-time-search-size")}

    def own(route, step, w):
        return sum(float(r["wall_s"]) for r in rows if (r["route"], r["step"], r["workload"]) == (route, step, w))

    def total(route, steps, w):
        return sum(own(route, s, w) + own(route, s, SHARED[w]) for s in steps)

    def line(name, cells):
        return f"{name} & " + " & ".join(cells) + r" \\"

    have = [w for w in WORKLOADS if w in size]       # a run that did not measure a dataset: its column shows --
    for w in WORKLOADS:
        if w not in have:
            print(f"{w}: not in this run: its column shows --")

    def each(fn):
        return [fn(w) if w in have else "--" for w in WORKLOADS]

    def per_dataset(route, step):
        """a step two workloads share spans their columns"""
        ldbc, imdb = own(route, step, "LDBC"), own(route, step, "IMDb")
        return [rf"\multicolumn{{2}}{{c}}{{{human(ldbc)}}}", human(imdb) if "JOB" in have else "--"]

    def per_workload(route, step):
        return each(lambda w: human(own(route, step, w)))

    def compose_and_cost(w):
        """the measure route's compose and cost-layouts rows (beside it, not in its total); -- when there are none"""
        rs = [r for r in rows if r["route"] == "measure" and r["step"] not in ("build", "run") and r["workload"] == w]
        return human(sum(float(r["wall_s"]) for r in rs)) if rs else "--"

    measure = {w: total("measure", ("build", "run"), w) for w in have}
    predict = {w: total("predict", ("statistics", "tally", "predict"), w) for w in have}
    mix = {(r["workload"], r["step"]): r for r in rows if r["route"] == "mix"}

    def verify(w):
        r = mix[(w, "verify")]
        if r["proven"] == "yes":
            return human(float(r["wall_s"]))
        return rf"stopped$^\dagger$"

    gaps = [f"{float(mix[(w, 'verify')]['gap']) * 100:.0f}\\%" for w in have if mix[(w, "verify")]["proven"] != "yes"]
    head = lambda text: rf"\multicolumn{{4}}{{@{{}}l}}{{\emph{{{text}}}}} \\"      # noqa: E731
    lines = [r"% GENERATED by tab_run_time.py (gs-paper evidence/run-time/) from run-time.csv -- do not edit",
             r"\begin{tabular}{@{}lrrr@{}}", r"\toprule",
             r" & Interactive & BI & JOB \\", r"\midrule",
             line("Queries", each(lambda w: size[w]["queries"])),
             line("Candidate plans", each(lambda w: size[w]["plans"])),
             r"\midrule",
             head("Measure: build and run the seven stores"),
             line("Build the stores", per_dataset("measure", "build")),
             line("Run the workload", per_workload("measure", "run")),
             line("Total", each(lambda w: human(measure[w]))),
             line("Compose and cost the 49", each(compose_and_cost)),
             r"\midrule",
             head("Predict: no store"),
             line("Statistics", per_dataset("predict", "statistics")),
             line("Tallies, seven settings", per_dataset("predict", "tally")),
             line("Predict the 49", per_workload("predict", "predict")),
             line("Total", each(lambda w: human(predict[w]))),
             line("Measure / predict", each(lambda w: f"{measure[w] / predict[w]:.1f}$\\times$")),
             r"\midrule",
             head("Best mix, op-byte cost: no store"),
             line("Find, fixed plans (greedy)", each(lambda w: human(float(mix[(w, "find, fixed plan")]["wall_s"])))),
             line("Find, plans re-picked", each(lambda w: human(float(mix[(w, "find, plans re-picked")]["wall_s"])))),
             line("Verify (branch and bound)", each(verify)),
             r"\bottomrule", r"\end{tabular}"]
    if gaps:
        lines.append(rf"\\[2pt]{{\scriptsize $^\dagger$ unproven: stopped early, the bound {', '.join(gaps)} below the mix found}}")
    lines.append("")
    out = out_dir / "tables" / "run-time.tex"
    write_table(out, lines, 'What choosing among the 49 uniform layouts costs, by measuring and by predicting, and what finding the best mix costs (LDBC SF3; IMDb full).')


if __name__ == "__main__":
    main()
