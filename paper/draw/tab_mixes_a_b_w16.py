#!/usr/bin/env python3
# released from gs-paper at 4b5c722 (evidence/pareto-and-fixed-i01/tab_mixes_a_b_w16.py); edit it there, then run evidence/release_draw.py
"""Paper table: the setting of each part in mixes A and B of the W16 front (the tabular only; main.tex holds the table,
caption and label).

  tables/pareto-and-fixed-w16-mixes.tex

A and B are the figure's own marks (MARKS in fig_pareto_and_fixed_w16.py): the best mix per type within 2x and 5x
Sp-Co's bytes. One row per part (6 vertex property groups, 15 edge types, the index), and per mix its setting (Sp,
Co, Ch64k; bold where A and B differ) and its share of the mix's wops and bytes, in percent (each column sums to 100).
Under the header, each mix's wops and bytes as multiples of Sp-Co's. wops = G + 1.1 S + 0.01 N + P + D; bytes =
read (misses included) + written.

Reads only its table, pareto-and-fixed-i01.csv (the front rows and the nine uniform layouts).

    python tab_mixes_a_b_w16.py --data <dir of the tables> --out <dir>    # -> <out>/tables/pareto-and-fixed-w16-mixes.tex
"""
from common import args, read_table
from fig_pareto_and_fixed_w16 import LISTS, MARKS, PROPS, SHORT



def pct(part, total):
    """a part's share of a mix's total, in percent, as text"""
    v = 100 * part / total
    return "<0.1" if 0 < v < 0.05 else f"{v:.1f}"


def main():
    data, out_dir = args(__doc__)
    table = sorted(read_table(data, "pareto-and-fixed-i01"), key=lambda r: (r["kind"], r["line"]))
    front = [r for r in table if r["kind"] == "front"]
    ref = next(r for r in table if r["kind"] == "uniform" and r["name"] == "Sp-Co")
    rb, ro = float(ref["bytes"]), float(ref["ops"])
    # the same pick as the figure's: the last front mix (fewest wops) within the byte limit
    marks = [(name, [r for r in front if float(r["bytes"]) / rb <= lim * (1 + 1e-9)][-1]) for name, lim in MARKS]
    (na, a), (nb, b) = marks
    for _, m in marks:   # the parts and the index add up to the mix's totals (the shares sum to 100%)
        for k in ("ops", "bytes"):
            s = sum(float(m[c]) for c in m if c.startswith(f"{k}_") and m[c] != "")
            if abs(s / float(m[k]) - 1) > 1e-9:
                raise SystemExit(f"mix {m['line']}: its parts' {k} sum to {s}, not {m[k]}")

    def cells(m, col, bold):
        ops, byt = float(m[f"ops_{col}"] or 0), float(m[f"bytes_{col}"] or 0)
        setting = SHORT[m[f"setting_{col}"]] if f"setting_{col}" in m else "--"
        if bold:
            setting = f"\\textbf{{{setting}}}"
        return f"{setting} & {pct(ops, float(m['ops']))} & {pct(byt, float(m['bytes']))}"

    def row(label, col):
        bold = f"setting_{col}" in a and a[f"setting_{col}"] != b[f"setting_{col}"]
        return f"{label} & {cells(a, col, bold)} & {cells(b, col, bold)} \\\\"

    lines = [r"% GENERATED by tab_mixes_a_b_w16.py (gs-paper evidence/pareto-and-fixed-i01/) from"
             r" pareto-and-fixed-i01.csv -- do not edit",
             r"{\setlength{\tabcolsep}{3pt}%   (this table only: one paper column)", r"\begin{tabular}{@{}l@{\hspace{6pt}}lrr@{\hspace{10pt}}lrr@{}}", r"\toprule",
             f"& \\multicolumn{{3}}{{c}}{{Mix {na}}} & \\multicolumn{{3}}{{c@{{}}}}{{Mix {nb}}} \\\\",
             r"\cmidrule(lr){2-4}\cmidrule(l){5-7}",
             r"Part & & wops\,\% & bytes\,\% & & wops\,\% & bytes\,\% \\",
             r"\midrule",
             f"$\\times$ Sp-Co & & {float(a['ops']) / ro:.3f}$\\times$ & {float(a['bytes']) / rb:.2f}$\\times$"
             f" & & {float(b['ops']) / ro:.3f}$\\times$ & {float(b['bytes']) / rb:.2f}$\\times$ \\\\",
             r"\midrule", r"\multicolumn{7}{@{}l}{\emph{Vertex properties}} \\"]
    lines += [row(p, f"props_{p}") for p in PROPS]
    lines += [r"\midrule", r"\multicolumn{7}{@{}l}{\emph{Edge lists}} \\"]
    lines += [row(e, f"adj_{e}") for e in LISTS]
    lines += [r"\midrule", row("Index", "index"), r"\bottomrule", r"\end{tabular}}", ""]
    out = out_dir / "tables" / "pareto-and-fixed-w16-mixes.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
