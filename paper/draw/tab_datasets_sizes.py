#!/usr/bin/env python3
# released from gs-paper at 4b5c722 (evidence/datasets/tab_datasets_sizes.py); edit it there, then run evidence/release_draw.py
"""Paper table (the appendix, tab:datasets-sizes): each dataset's store size under the seven layouts that give properties and
adjacency one setting: Sp-Sp, Co-Co and ChK-ChK at K = 1, 4, 16, 64 and 256 KB (the tabular only).

  tables/datasets-sizes.tex

Size = the store's SST bytes in GB (10^9 bytes), RocksDB without compression, from the store manifest of each built
store's run record. The smallest size per dataset is bold.

Reads only its table, datasets-sizes.csv: per dataset (row: the table's order) and layout, the SST bytes.

    python tab_datasets_sizes.py --data <dir of datasets-sizes.csv> --out <dir>   # -> <out>/tables/datasets-sizes.tex
"""
from common import args, read_table

LAYOUTS = (("props_split_adj_split", "Sp-Sp"), ("props_condensed_adj_condensed", "Co-Co"),
           ("props_chunked_c1k_adj_chunked_c1k", "1\\,KB"), ("props_chunked_c4k_adj_chunked_c4k", "4\\,KB"),
           ("props_chunked_c16k_adj_chunked_c16k", "16\\,KB"), ("props_chunked_adj_chunked", "64\\,KB"),
           ("props_chunked_c256k_adj_chunked_c256k", "256\\,KB"))


def main():
    data, out_dir = args(__doc__)
    by_row = {}
    for r in read_table(data, "datasets-sizes"):
        by_row.setdefault(int(r["row"]), {})[r["layout"]] = r
    lines = [r"% GENERATED by tab_datasets_sizes.py (gs-paper evidence/datasets/) from datasets-sizes.csv -- do not edit",
             r"\begin{tabular}{@{}lrrrrrrr@{}}", r"\toprule",
             r" & & & \multicolumn{5}{c@{}}{ChK-ChK, chunk size K} \\", r"\cmidrule(l){4-8}",
             "Dataset (GB) & " + " & ".join(label for _, label in LAYOUTS) + r" \\", r"\midrule"]
    for i in sorted(by_row):
        rows = by_row[i]
        missing = [c for c, _ in LAYOUTS if c not in rows]
        if missing or len({r["dataset"] for r in rows.values()}) != 1:
            raise SystemExit(f"row {i}: missing {missing}, or the layouts name different datasets")
        size = {c: int(rows[c]["sst_bytes"]) / 1e9 for c, _ in LAYOUTS}
        low = min(round(v, 2) for v in size.values())
        cells = [(rf"\textbf{{{v:.2f}}}" if round(v, 2) == low else f"{v:.2f}") for v in (size[c] for c, _ in LAYOUTS)]
        lines.append(f"{next(iter(rows.values()))['dataset']} & " + " & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", ""]
    out = out_dir / "tables" / "datasets-sizes.tex"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines))
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
