#!/usr/bin/env python3
"""The rescore stage's summary (run-predict-statistics-uniform-params.sh --stages rescore): one row per (param set,
cardinality rules on or off, model) from each run's layout report (python -m kvcost.predict_accuracy.layouts), plus the count of layouts
past 30x the cheapest, predicted and measured, which picks.csv does not hold.

    python3 experiments/predict_statistics/rescore_summary.py --root <out>/rescore --stats F [--rules-off a,b]
    -> <root>/summary.csv, <root>/summary.md
"""
import argparse
import csv
import os
import sys

from kvevaluator.paths import _under_results

SETS = (("ldbc-params", "LDBC's params 1-5"), ("uniform", "the uniform set"))
FAR = 30.0         # a layout this many times the cheapest is "past 30x"
COLUMNS = ["param_set", "rules", "currency", "layouts", "spearman", "named", "named_measured_over_best",
           "measured_rank_of_named", "measured_best", "queries_hit", "queries", "predicted_past_30x", "measured_past_30x"]


def shown(path):
    """a file by its place under paper-results/ (no machine path), else as given"""
    rel = _under_results(path)
    return f"<paper-results>/{rel}" if rel else path


def one_run(d):
    """[summary rows] of one --layouts output dir (its layout_choice/), one per currency"""
    with open(os.path.join(d, "picks.csv"), newline="") as f:
        picks = list(csv.DictReader(f))
    with open(os.path.join(d, "totals.csv"), newline="") as f:
        totals = list(csv.DictReader(f))
    rows = []
    for w in [p for p in picks if p["kind"] == "workload"]:
        cur = w["currency"]
        qs = [p for p in picks if p["kind"] == "query" and p["currency"] == cur]
        t = [r for r in totals if r["currency"] == cur]
        pmin, mmin = min(float(r["predicted"]) for r in t), min(float(r["measured"]) for r in t)
        rows.append({"currency": cur, "layouts": w["layouts"], "spearman": w["spearman"], "named": w["named_short"],
                     "named_measured_over_best": w["named_measured_over_best"],
                     "measured_rank_of_named": w["measured_rank_of_named"], "measured_best": w["measured_best_short"],
                     "queries_hit": sum(int(p["hit"]) for p in qs), "queries": len(qs),
                     "predicted_past_30x": sum(float(r["predicted"]) > FAR * pmin for r in t),
                     "measured_past_30x": sum(float(r["measured"]) > FAR * mmin for r in t)})
    return rows


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", required=True, help="the rescore stage's output dir")
    ap.add_argument("--stats", required=True, help="the statistics predict read (named in summary.md)")
    ap.add_argument("--rules-off", default="", help="the switches of the rules-off pass (named in summary.md)")
    a = ap.parse_args(argv)
    rules = ["on"] + (["off"] if a.rules_off else [])
    out = []
    for s, _ in SETS:
        for r in rules:
            d = os.path.join(a.root, f"{s}-rules-{r}", "layout_choice")
            out += [{"param_set": s, "rules": r, **row} for row in one_run(d)]
    if len(out) != len(SETS) * len(rules) * 2:
        sys.exit(f"rescore_summary: {len(out)} rows, expected {len(SETS) * len(rules) * 2} -- REFUSED")
    with open(os.path.join(a.root, "summary.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, COLUMNS, lineterminator="\n")
        w.writeheader()
        w.writerows(out)
    by = {(r["param_set"], r["rules"], r["currency"]): r for r in out}
    L = ["> Generated by "
         "`experiments/predict_statistics/rescore_summary.py`; data in this dir.", "",
         "# Predict on two param sets, the cardinality rules on and off", "",
         f"I02 on the 49 layouts, predicted from `{shown(a.stats)}`; each scored by `python -m kvcost.predict_accuracy.layouts` against "
         "the measured side an earlier run kept (`--measured-table`). Rules off: "
         + (f"`{a.rules_off}`." if a.rules_off else "none (one pass)."), "",
         "| params | model | Spearman (49): " + " -> ".join(f"rules {r}" for r in rules[::-1]) +
         " | pick (measured x over best, its rank) | queries hit | layouts past 30x, predicted / measured |",
         "|---|---|---|---|---|---|"]
    for s, label in SETS:
        for cur in ("wops_bytes4k", "wops"):
            rr = [by[(s, r, cur)] for r in rules[::-1]]
            spearman = " -> ".join("%.3f" % float(r["spearman"]) for r in rr)
            pick = " -> ".join("%s %.4fx (rank %s)" % (r["named"], float(r["named_measured_over_best"]),
                                                       r["measured_rank_of_named"]) for r in rr)
            hits = " -> ".join(str(r["queries_hit"]) for r in rr)
            far = " -> ".join("%s / %s" % (r["predicted_past_30x"], r["measured_past_30x"]) for r in rr)
            L.append(f"| {label} | {cur} | {spearman} | {pick} | {hits} of {rr[0]['queries']} | {far} |")
    with open(os.path.join(a.root, "summary.md"), "w") as f:
        f.write("\n".join(L) + "\n")
    print(f"rescore_summary: {len(out)} rows -> {a.root}/summary.csv, summary.md")
    return 0


if __name__ == "__main__":
    sys.exit(main())
