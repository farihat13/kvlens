#!/usr/bin/env python3
"""Run every ENGINE-FAITHFUL plan and compare it to the live engine's measured /kvstats: the engine-fidelity
validation table, one CSV regenerated by one command.

What it reports, per (query, db):

  S, G, N        sim vs live, and a ratio for EACH, not only the S+G total: a single ratio hides a bad component
                 whenever the other dominates (a plan 99% GET can fit in total with its SEEKs at 0.57x).
  rows_match     do the engine plan's rows agree with the OPTIMAL plan's for the same query? The two take
                 different access paths to the same answer, so a mismatch is a plan bug (a plan can post a
                 great ratio while computing the wrong result).
  fit            YES when EVERY component (S, G and N) is within FIT_REL of live; "validated" is this column.
  status         suite (ENGINE registry) or draft (ENGINE_DRAFT; only run with --drafts).
  split          microbench blind holdout: `train` = the one param per shape the plan's author may see
                 (live_workloads.train_param), `test` = held out. LDBC: `seen` = the params in view while the
                 plans were written; `holdout` = params first measured after the plans froze.
  split_residual_G  Dgraph only: the GETs Dgraph pays for split posting lists that our store can't
                 (DGRAPH_SPLIT_PARTS); residual_exact: YES when the whole gap is exactly that residual.
  opt_S/G/N      the OPTIMAL plan's counts on the same store.
  bound          the <=-engine bound: YES when the optimal plan's weighted ops (python/kvevaluator/weights.py)
                 <= the live engine's; meaningful only where the two answer the same question.
  cols_missing   the LDBC output columns the engine plan's rows do not carry: non-empty -> rows_match is
                 PARTIAL, a failure. live_cols_missing: the same for the engine's parsed answer (reported only).
  sim_<lane>, live_<lane>   the sim's raw byte lanes (the C++ store's encoded bytes) and the live /kvstats byte
                 lanes, carried raw, not compared here (which sim lanes a live counter covers is per engine).
  answer_source  stored (identity matches), fetched (asked now), or stored-unchecked (--stored-answers).
  run_id, git_sha  the run that wrote the row and the code it ran (`-dirty`: uncommitted changes).

Both plans run on the C++ evaluator: the engine plan on the db's C++ ENGINE store (store_identity.CPP_ENGINE_FORMATS),
the optimal plan on the compared format's own store; tests/gates/check_engine_plans.py --backend cpp and
check_engine_ops.py hold the Python twins to the same counts and answers. Live baselines come from live_kvstats.csv
(`measure.py`, servers needed); this file only reads it, so it runs offline.

RUN MORE THAN ONE PARAM: param 1 is the degenerate case for every message-anchored query (a depth-0 Post, whose reply
chase is empty); plans fitted to it alone returned wrong answers at other params. The param files are stratified
6-per-reply-depth over depths 0-5, so `--param 1,7,13,19,25,31` is one per depth.

Usage:
  python3 validate.py                              # every cell, every param in the baseline
  python3 validate.py --query ic2                  # one query
  python3 validate.py --param 1,7,13,19,25,31      # one anchor per reply depth
  python3 validate.py --live                       # ALSO diff rows vs the engines' (stored) answers
  python3 validate.py --live --refresh-answers     # ... asking every engine again
  python3 validate.py --live --stored-answers      # ... offline: stored answers only, never ask (unchecked)
  python3 validate.py --live --from paper-results  # offline, on the paper's capture: its answers checked, no engine
  python3 validate.py --drafts                     # ALSO run the ENGINE_DRAFT plans (status=draft)
  python3 validate.py --family microbench --split train   # what a plan author may check
  python3 validate.py --family microbench                 # train + held-out params
"""
