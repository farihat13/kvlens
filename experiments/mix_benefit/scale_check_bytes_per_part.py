#!/usr/bin/env python3
"""Where a layout's bytes move between two scales: I01's cost on each adjacency part with every list on one setting
(Split, Condensed, Chunked at 64 KB, Chunked at 4 KB; properties Condensed), at the small and at the large scale.
I01's own frequencies, reported params, each query at the plan that layout picks from the grid's own held-out rows.
Every cost is composed from uniform captures; no store is opened.

    python3 experiments/mix_benefit/scale_check_bytes_per_part.py --small-c64k <grid> --small-c4k <grid> \\
        --large-c64k <grid> --large-c4k <grid> --out DIR
        -> <out>/bytes_per_part.csv   one row per (scale, part, list setting, chunk bytes): bytes, weighted ops, raw channels
           <out>/bytes_per_part.md    bytes over the same part on Split lists, per part and scale"""
import argparse
import csv
import os
import sys
from collections import defaultdict

import scale_check_common as C
from scale_check_common import compose

RAW = list(compose.MEASURES) + list(compose.CHANNELS)


def per_part(grid, setting):
    """{adjacency unit: {channel: I01's frequency-weighted sum}} with every list on `setting`"""
    data, w, units = C.load_w16(grid)
    assign = C.lists_on(units, setting)
    tot = defaultdict(lambda: defaultdict(float))
    for fam, q, often, params in w["items"]:
        d = data[(fam, q)]
        qunits = {u for per in d["cost"].values() for u in per if u is not None}
        cost = compose.query_cost(d, compose.params_of(d, params), assign, qunits, by_unit=True)
        if cost[0] is None:
            continue
        for u, vec in cost[1].items():
            if u is not None and u[0] == "adj":
                cc = compose.currencies(vec)
                for x in RAW:
                    tot[u][x] += often * vec[x]
                tot[u]["bytes"] += often * cc["bytes"]
                tot[u]["ops"] += often * cc["ops"]
    return data.sf, tot


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    for scale in ("small", "large"):
        for chunk in ("c64k", "c4k"):
            ap.add_argument(f"--{scale}-{chunk}", required=True, help=f"the {scale} scale's nine cells, Chunked at {chunk[1:-1]} KB")
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    rows, table = [], {}
    for scale in ("small", "large"):
        for chunk, grid in (("65536", getattr(a, f"{scale}_c64k")), ("4096", getattr(a, f"{scale}_c4k"))):
            for setting in C.LIST_SETTINGS:
                if setting != "chunked" and chunk == "4096":
                    continue                                    # Split and Condensed lists have no chunk size
                sf, tot = per_part(grid, setting)
                for u in sorted(tot):
                    t = tot[u]
                    rows.append({"workload_id": "i01", "scale": f"sf{sf}", "part": C.part_name(u), "lists": setting,
                                 "chunk_bytes": chunk if setting == "chunked" else "", "total_bytes": round(t["bytes"], 3),
                                 "total_ops": round(t["ops"], 3), **{x: round(t[x], 3) for x in RAW}})
                    table[(C.part_name(u), f"sf{sf}", setting, chunk if setting == "chunked" else "")] = t["bytes"]
    os.makedirs(a.out, exist_ok=True)
    with open(os.path.join(a.out, "bytes_per_part.csv"), "w", newline="") as f:
        wr = csv.DictWriter(f, fieldnames=list(rows[0]), lineterminator="\n")
        wr.writeheader()
        wr.writerows(rows)
    scales = list(dict.fromkeys(r["scale"] for r in rows))
    L = ["# I01's bytes per adjacency part, by list setting and scale", "",
         "> Generated by "
         "`experiments/mix_benefit/scale_check_bytes_per_part.py`.", "",
         "Bytes read on the part with every list on one setting (properties Condensed), over the same part on Split lists. "
         "I01's frequencies, reported params, composed.", "",
         "| part | scale | on Split lists, GB | Condensed / Split | Chunked 64 KB / Split | Chunked 4 KB / Split |", "|---|---|---|---|---|---|"]
    for part in sorted({k[0] for k in table}):
        for sf in scales:
            ref = table.get((part, sf, "split", ""))
            if not ref:
                continue
            r = lambda s, c: table.get((part, sf, s, c), 0.0) / ref
            L.append(f"| {part} lists | {sf.upper()} | {ref / 1e9:,.2f} | {r('condensed', ''):.2f} | {r('chunked', '65536'):.1f} | {r('chunked', '4096'):.1f} |")
    with open(os.path.join(a.out, "bytes_per_part.md"), "w") as f:
        f.write("\n".join(L) + "\n")
    print("\n".join(L[6:]))
    print(f"[bytes_per_part] {len(rows)} rows, {len({r['part'] for r in rows})} parts")
    return 0


if __name__ == "__main__":
    sys.exit(main())
