"""Predict mode on writes: each write op's estimate (levels predicted, predicted_anchor) against the measured run, per layout.

Reads <out>/steps.csv (kvevaluator predict --accuracy on the write requests, run/predict-accuracy.sh --family writes)
and writes <out>/write_ratios.csv and <out>/write_summary.md. Every number is a sum over the requests' write steps
(each plan at its params). The currencies, priced from the lanes through cost_models: wops = the reads weighted + P +
D; bytes = the key and value bytes read (the miss keys included) + the bytes written; wops_bytes4k = wops + bytes /
4,096.
    python -m kvcost.predict_accuracy.write_report <out> "<binary>"
"""
import csv
import os
import sys

from kvcost.layout_cost import cost_models as CM
from kvcost.layout_cost import compose

SOURCES = ("measured", "predicted", "predicted_anchor")
from kvevaluator.plans.ir.capabilities import KV_WRITE_OPS as WRITE_OPS  # (the op table's writes)


def layout_of(cell):
    """props_split_adj_condensed -> Sp-Co (kvevaluator.layouts.name_of); anything that is no cell id keeps its name"""
    from kvevaluator import layouts as L
    try:
        return L.name_of(cell)
    except ValueError:
        return cell


def vector(r):
    """a write step's lanes as a priced vector (compose.write_vector: its own reads as write_rmw_*, its PUTs, DELs and
    the bytes they write; the read channels 0), under the measured chunk view: an estimate against the bytes its run
    found"""
    return {"read_ops": 0.0, "read_bytes": 0.0, "miss_key_bytes": 0.0, **compose.write_vector(r)}


def totals(rows, key):
    """(key..., source) -> {wops, bytes, wops_bytes4k, P, D}, summed over the rows"""
    out = {}
    for r in rows:
        k = key(r) + (r["source"],)
        t = out.setdefault(k, {"wops": 0.0, "bytes": 0.0, "P": 0.0, "D": 0.0})
        v = vector(r)
        t["wops"] += CM.cost(v, "wops")
        t["bytes"] += CM.cost(v, "bytes")
        t["P"] += float(r["P"])
        t["D"] += float(r["D"])
    for t in out.values():
        t["wops_bytes4k"] = CM.wops_bytes4k(t["wops"], t["bytes"])
    return out


def ratio(est, meas):
    return est / meas if meas > 0 else (1.0 if est == 0 else float("inf"))


def table(rows, key, names, layouts):
    t = totals(rows, key)
    groups = sorted({k[:-1] for k in t}, key=lambda g: (g[:-1], layouts.index(g[-1])))
    head = ("| " + " | ".join(names) + " | wops measured | wops predicted (ratio) | wops predicted_anchor (ratio) | wops_bytes4k measured"
            " | wops_bytes4k predicted (ratio) | wops_bytes4k predicted_anchor (ratio) | P measured / predicted | D measured / predicted |")
    lines = [head, "|" + "---|" * (len(names) + 8)]
    out = []
    for g in groups:
        m, b, ba = (t.get(g + (s,)) for s in SOURCES)
        if not (m and b and ba):
            continue
        cells = [str(x) for x in g]
        for cur in ("wops", "wops_bytes4k"):
            cells.append(f"{m[cur]:.1f}")
            cells.append(f"{b[cur]:.1f} ({ratio(b[cur], m[cur]):.2f})")
            cells.append(f"{ba[cur]:.1f} ({ratio(ba[cur], m[cur]):.2f})")
        cells.append(f"{m['P']:.0f} / {b['P']:.1f}")
        cells.append(f"{m['D']:.0f} / {b['D']:.1f}")
        lines.append("| " + " | ".join(cells) + " |")
        out.append(dict(zip(names, g), **{f"{s}_{c}": t[g + (s,)][c] for s in SOURCES
                                          for c in ("wops", "wops_bytes4k", "bytes", "P", "D")}))
    return lines, out


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    out_dir, binary = argv[0], argv[1] if len(argv) > 1 else ""
    rows = [r for r in csv.DictReader(open(os.path.join(out_dir, "steps.csv"))) if r["op"] in WRITE_OPS]
    if not rows:
        raise SystemExit(f"write_report: no write step in {out_dir}/steps.csv")
    for r in rows:
        r["layout"] = layout_of(r["cell"])
    layouts = sorted({r["layout"] for r in rows})
    by_op, op_rows = table(rows, lambda r: (r["op"], r["layout"]), ["op", "layout"], layouts)
    by_plan, plan_rows = table(rows, lambda r: (r["query"], r["layout"]), ["plan", "layout"], layouts)
    params = len({(r["query"], r["param"]) for r in rows if r["source"] == "measured"})
    md = ["> Generated by "
          "`python -m kvcost.predict_accuracy.write_report`.", "",
          f"# Predict mode on writes: estimate against measured (binary {binary})", "",
          f"{len({r['query'] for r in rows})} write plans, {params} (plan, param) pairs, on {len(layouts)} layouts; "
          "each number sums the write steps over the params. predicted: the population statistics; predicted_anchor: predicted plus the "
          "anchor statistics (a person's own knows degree and message count). wops = G + 1.1 S + 0.01 N + P + D; "
          "wops_bytes4k = wops + bytes / 4,096, bytes = read (miss keys included) + written. Ratio = estimate / measured.",
          "", "## Per write op", ""] + by_op + ["", "## Per plan", ""] + by_plan + [""]
    with open(os.path.join(out_dir, "write_summary.md"), "w") as f:
        f.write("\n".join(md))
    with open(os.path.join(out_dir, "write_ratios.csv"), "w", newline="") as f:
        cols = ["kind", "op_or_plan", "layout"] + [k for k in op_rows[0] if k not in ("op", "layout")]
        w = csv.DictWriter(f, fieldnames=cols)
        w.writeheader()
        for kind, rs, name in (("op", op_rows, "op"), ("plan", plan_rows, "plan")):
            for r in rs:
                d = {k: v for k, v in r.items() if k not in (name, "layout")}
                w.writerow(dict(kind=kind, op_or_plan=r[name], layout=r["layout"], **d))
    print(f"write_report: {len(rows)} step rows, {len(op_rows)} (op, layout) and {len(plan_rows)} (plan, layout) groups")


if __name__ == "__main__":
    main()
