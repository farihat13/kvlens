def family_of(qname):
    """The param family a query reads (None for the no-param queries)."""
    return _P[qname][0]


def param_path(sf, family):
    return os.path.join(params_in("ldbc", sf, "microbench"), f"{family}.txt")


def param_rows(sf, qname):
    """All raw rows for a query's family (dicts keyed by the header); a no-param query yields one empty row.
    A missing file is regenerated (deterministic, so byte-identical; needs the SF's LDBC CSVs).
    """
    family, _ = _P[qname]
    if family is None:
        return [{}]
    path = param_path(sf, family)
    if not os.path.exists(path):
        import sys
        from kvevaluator.workloads.microbench import genparams
        print(f"[microbench] params for sf{sf} not found -- generating "
              f"(deterministic; see genparams.py)", file=sys.stderr)
        genparams.main(["--sf", str(sf)])
    with open(path) as f:
        header = f.readline().rstrip("\n").split("|")
        return [dict(zip(header, line.rstrip("\n").split("|"))) for line in f]


def args_from_row(qname, r):
    _, build = _P[qname]
    return build(r) if build else {}


def query_params(sf, qname, count=None):
    """Arg dicts for the first `count` params of a query (all when count=None); the same contract as the other workloads."""
    rows = param_rows(sf, qname)
    if count:
        rows = rows[:count]
    return [args_from_row(qname, r) for r in rows]
