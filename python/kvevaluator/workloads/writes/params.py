"""Substitution parameters for the writes workload: each query reads one family of its own genparams."""
import os

from kvevaluator.workloads.writes import genparams
from kvevaluator.workloads.writes.genparams import param_path
from kvevaluator.workloads.writes.ldbc.queries import (IU1_COMPANIES, IU1_FRIENDS, IU1_TAGS, IU1_UNIS, IU4_TAGS,
                                                        IU6_TAGS, IU7_TAGS)

def _numbered(r, param, column, n):
    """param1..param<n> from the columns column1..column<n> (a numbered target list, genparams.TARGETS)."""
    return {f"{param}{i}": r[f"{column}{i}"] for i in range(1, n + 1)}


# query -> (family, args builder). Every family is generated by this workload's own genparams,
# for the reasons that file documents: the delete anchors need TOTAL incident degree (not knows
# degree), and the edge families need the STORED direction (not an undirected neighbour set).
_P = {
    "w_upd_plain":    ("person_incident", lambda r: {"person": r["personId"]}),
    "w_upd_indexed":  ("person_incident", lambda r: {"person": r["personId"]}),
    "w_upd_dated":    ("person_incident", lambda r: {"person": r["personId"]}),
    "w_upd_multi":    ("person_incident", lambda r: {"person": r["personId"]}),
    "w_upd_edge":     ("knows_edges", lambda r: {"src": r["srcId"], "dst": r["dstId"]}),
    "w_ins_v_min":    ("person_incident", lambda r: {"person": r["personId"]}),
    "w_ins_v_full":   ("person_incident", lambda r: {"person": r["personId"]}),
    "w_ins_e_plain":  ("new_pairs", lambda r: {"src": r["srcId"], "dst": r["dstId"]}),
    "w_ins_e_facet":  ("new_pairs", lambda r: {"src": r["srcId"], "dst": r["dstId"]}),
    "w_del_v_record": ("person_incident", lambda r: {"person": r["personId"]}),
    "w_del_v":        ("person_incident", lambda r: {"person": r["personId"]}),
    "w_del_e":        ("knows_edges", lambda r: {"src": r["srcId"], "dst": r["dstId"]}),
    # LDBC insert operations (IU1-IU8). The person-anchored ones reuse person_incident so an
    # operation's cost can be read against the anchor's connectivity; IU8 needs a pair that is not
    # already adjacent, which is exactly what new_pairs holds.
    "iu1": ("person_incident", lambda r: {"person": r["personId"], "city": r["cityId"],
                                           **_numbered(r, "friend", "friend", IU1_FRIENDS - 1),
                                           **_numbered(r, "interest", "interest", IU1_TAGS),
                                           **_numbered(r, "university", "university", IU1_UNIS),
                                           **_numbered(r, "company", "company", IU1_COMPANIES)}),
    "iu2": ("person_incident", lambda r: {"person": r["personId"], "post": r["likePostId"]}),
    "iu3": ("person_incident", lambda r: {"person": r["personId"], "comment": r["likeCommentId"]}),
    "iu4": ("person_incident", lambda r: {"person": r["personId"], **_numbered(r, "tag", "forumTag", IU4_TAGS)}),
    "iu5": ("person_incident", lambda r: {"person": r["personId"], "forum": r["memberForumId"]}),
    "iu6": ("person_incident", lambda r: {"person": r["personId"], "forum": r["postForumId"],
                                           "country": r["postCountryId"], **_numbered(r, "tag", "postTag", IU6_TAGS)}),
    "iu7": ("person_incident", lambda r: {"person": r["personId"], "replyTo": r["replyToId"],
                                           "country": r["commentCountryId"],
                                           **_numbered(r, "tag", "commentTag", IU7_TAGS)}),
    "iu8": ("new_pairs", lambda r: {"src": r["srcId"], "dst": r["dstId"]}),
}


def family_of(qname):
    return _P[qname][0]


def param_rows(sf, qname):
    """The raw rows for a query's family. A missing or stale-header file is regenerated (deterministic, so
    byte-identical to the committed one).
    """
    family, _build = _P[qname]
    path = param_path(sf, family)
    if not os.path.exists(path):
        import sys
        print(f"[writes] params for sf{sf} not found -- generating "
              f"(deterministic; see workloads/writes/genparams.py)", file=sys.stderr)
        genparams.main(["--sf", str(sf)])
    with open(path) as f:
        header = f.readline().rstrip("\n").split("|")
        rows = [dict(zip(header, line.rstrip("\n").split("|"))) for line in f]
    if family == "person_incident" and not {"replyToId", "likePostId", "friend4", "interest1", "commentTag1"} <= set(header):
        # a file without today's columns: regenerate -- deterministic, so the refreshed file differs only by the new columns
        import sys
        print(f"[writes] stale params header for sf{sf} -- regenerating", file=sys.stderr)
        genparams.main(["--sf", str(sf)])
        return param_rows(sf, qname)
    return rows


def args_from_row(qname, r):
    return _P[qname][1](r)


def query_params(sf, qname, count=None):
    """Arg dicts for the first `count` params (all when count=None); the same contract as the other workloads' query_params."""
    rows = param_rows(sf, qname)
    if count:
        rows = rows[:count]
    return [args_from_row(qname, r) for r in rows]
