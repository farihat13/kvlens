#!/usr/bin/env python3
"""What made a LinkBench data dir, and its checksums: <data>/manifest.json (called by generate.sh, beside it; read by
fetch.check). Records the tool's commit, the two seeds, the clock setting (the fixed value; a recorded clock's
file and sha256) and, per data file, lines and sha256. Opens no store.

  --write           write the manifest. With a recorded clock that has a `<trace>.json` beside it (the run it was
                    recovered from: lines and sha256 per file), the generated files must equal that run's, or rc 1.
  --same-settings   the dir's manifest must name the same clock value and the same recorded clock (by sha256), or rc 1:
                    data already there is never silently taken for data of another clock.

    python3 python/kvevaluator/datasets/linkbench/data_manifest.py --data DIR --tool DIR --clock MS [--clock-trace FILE] --write | --same-settings"""
import argparse
import hashlib
import json
import os
import re
import subprocess
import sys
from kvevaluator.paths import ROOT

EXP = str(ROOT)
FILES = ("nodes.jsonl", "links.jsonl", "requests.jsonl")
SEEDS = ("load_random_seed", "request_random_seed")


def digest(path):
    """(lines, sha256) of a file"""
    h, lines = hashlib.sha256(), 0
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 22), b""):
            h.update(block)
            lines += block.count(b"\n")
    return lines, h.hexdigest()


def clock_of(a):
    c = {"fixed_ms": a.clock, "trace": None}
    if a.clock_trace:
        path = os.path.abspath(a.clock_trace)
        c["trace"] = {"file": os.path.relpath(path, EXP) if path.startswith(EXP + os.sep) else path, "sha256": digest(path)[1]}
    return c


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--data", required=True)
    ap.add_argument("--tool", required=True, help="the LinkBench clone the data was generated with")
    ap.add_argument("--clock", required=True, type=int, help="the fixed clock value, ms")
    ap.add_argument("--clock-trace", help="the recorded clock file, when one was replayed")
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--write", action="store_true")
    g.add_argument("--same-settings", action="store_true")
    a = ap.parse_args()
    mpath, clock = os.path.join(a.data, "manifest.json"), clock_of(a)
    if a.same_settings:
        have = json.load(open(mpath)).get("clock")
        if have != clock:
            print(f"[linkbench data] {a.data} was generated with clock {json.dumps(have)}; this run asks for {json.dumps(clock)}. "
                  f"Give another --data dir, or the same clock setting.", file=sys.stderr)
            return 1
        return 0
    seeds = {}
    for cfg in ("linkbench.properties", "linkbench.request.properties"):
        path = os.path.join(a.data, cfg)
        if os.path.exists(path):
            for k, v in re.findall(r"^\s*(\w+)\s*=\s*(\S+)\s*$", open(path).read(), re.M):
                if k in SEEDS:
                    seeds[k] = v                   # a later line wins, as in the properties file
    files = {}
    for name in FILES:
        path = os.path.join(a.data, name)
        if os.path.exists(path):
            lines, sha = digest(path)
            files[name] = {"lines": lines, "sha256": sha}
    manifest = {"what": "LinkBench data generated by the LinkBench dataset's generate.sh: the same settings give the same bytes",
                "tool": {"repo": "https://github.com/facebookarchive/linkbench",
                         "commit": subprocess.run(["git", "-C", a.tool, "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip(),
                         "patched": "the wall-clock reads of LinkBenchLoad, NodeLoader and LinkBenchRequest -> LinkBenchClock.now()"},
                "seeds": seeds, "clock": clock, "files": files}
    reproduces = None
    side = (a.clock_trace or "") + ".json"
    if a.clock_trace and os.path.exists(side):
        want = json.load(open(side))["files"]
        bad = [n for n in sorted(want) if n in files and files[n] != {k: want[n][k] for k in ("lines", "sha256")}]
        missing = [n for n in sorted(want) if n not in files]
        reproduces = {"run": os.path.basename(side), "files_equal": len(want) - len(bad) - len(missing), "files": len(want)}
        manifest["reproduces"] = reproduces
        if bad:
            for n in bad:
                print(f"[linkbench data] {n}: {files[n]} is not the recorded run's {want[n]}", file=sys.stderr)
            print(f"[linkbench data] FAIL: {len(bad)} of {len(want)} files differ from the run the clock was recorded from; no manifest written", file=sys.stderr)
            return 1
    with open(mpath, "w") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)
        f.write("\n")
    print(f"[linkbench data] {mpath}: {len(files)} files, clock {clock['fixed_ms']} ms"
          + (f", recorded clock {clock['trace']['file']}" if clock["trace"] else "")
          + (f"; equal to the recorded run on {reproduces['files_equal']} of {reproduces['files']} files (sha256)" if reproduces else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main())
